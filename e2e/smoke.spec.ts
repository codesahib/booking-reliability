import { expect, test } from '@playwright/test'

// These flows use distinct stays: res-1001, res-1002, then a newly created booking.
// Playwright starts one fresh disposable database set for the entire smoke run.
test('identical retries expose baseline accounting and are suppressed after the fix', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Upcoming stays' })).toBeVisible()
  await page.getByRole('button', { name: 'Replay scenario', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Replay complete: 4 deliveries')
  await expect(page.getByTestId('duplicate-count')).toHaveText('2')
  await expect(page.getByTestId('violation-count')).toHaveText('3')
  await expect(page.getByTestId('ledger').locator('.history-row')).toHaveCount(3)
  await page.screenshot({ path: 'evidence/before-duplicate.png', fullPage: true })

  await page.getByRole('button', { name: '02 Hardened workflow' }).click()
  await expect(page.getByTestId('delivery-count')).toHaveText('0')
  await page.getByRole('button', { name: 'Replay scenario', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('2 duplicate')
  await expect(page.getByTestId('delivery-count')).toHaveText('4')
  await expect(page.getByTestId('duplicate-count')).toHaveText('0')
  await expect(page.getByTestId('violation-count')).toHaveText('0')
  await expect(page.getByTestId('ledger').locator('.history-row')).toHaveCount(1)
  await page.getByRole('button', { name: /duplicate event.*delivery #4/i }).click()
  await expect(page.getByTestId('incident-context')).toContainText('evt-payment')
  await expect(page.getByTestId('incident-context')).toContainText('res-1001')
  await page.screenshot({ path: 'evidence/after-duplicate.png', fullPage: true })

  await page.getByRole('button', { name: 'Send refund failure', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('human follow-up required')
  await expect(page.getByTestId('alert-count')).toHaveText('1')
  await page.getByRole('checkbox', { name: 'Open alerts only' }).check()
  await page.getByRole('button', { name: /refund failed.*res-1001/i }).click()
  await expect(page.getByTestId('incident-context')).toContainText('charge retained')
  await page.screenshot({ path: 'evidence/incident-refund-failure.png', fullPage: true })
})

test('an early refund is deferred, then reconciled when its charge arrives', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '02 Hardened workflow' }).click()
  await page.getByRole('button', { name: /Stillwater Point/ }).click()
  await page.getByRole('button', { name: 'Send refund success', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('no ledger entry created')
  await expect(page.getByTestId('ledger').locator('.history-row')).toHaveCount(0)
  await page.getByRole('button', { name: /refund deferred.*res-1002/i }).click()
  await expect(page.getByTestId('incident-context')).toContainText('deferred')
  await page.getByRole('button', { name: 'Send payment success', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('reconciled atomically')
  await expect(page.locator('.reservation.selected')).toContainText('refunded')
  await expect(page.getByTestId('ledger').locator('.history-row')).toHaveCount(2)
  await expect(page.getByTestId('violation-count')).toHaveText('0')
  await expect(page.getByTestId('incident-context')).toContainText('Closed automatically')
  await page.screenshot({ path: 'evidence/out-of-order-refund.png', fullPage: true })
})

test('booking confirmation, idempotent resubmission, and overlap error work on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '02 Hardened workflow' }).click()
  await page.getByText('Create a synthetic booking', { exact: true }).click()
  await page.getByRole('combobox', { name: 'Campsite', exact: true }).selectOption('ridge-03')
  await page.getByRole('button', { name: 'Confirm booking', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Confirmed synthetic reservation')
  const confirmation = await page.getByRole('status').textContent()
  await page.getByRole('button', { name: 'Confirm booking', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText(confirmation!)
  await page.getByLabel('Departure', { exact: true }).fill('2027-07-04')
  await page.getByRole('button', { name: 'Confirm booking', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('already reserved')
  await page.getByRole('button', { name: 'Send payment success', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('exactly once')
  await expect(page.locator('.reservation.selected')).toContainText('paid')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'evidence/mobile-booking.png', fullPage: true })
})
